import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { z } from "zod";
import * as contracts from "../src/index.ts";
import { eventCatalog } from "../src/index.ts";

type JsonSchema = {
  type?: string;
  format?: string;
  enum?: unknown[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
};

const root = new URL("../", import.meta.url);
const toJson = (schema: z.ZodType) =>
  JSON.stringify(z.toJSONSchema(schema, { io: "input" }), null, 2) + "\n";
const write = (path: string, text: string) => {
  writeFileSync(new URL(path, root), text);
};

rmSync(new URL("schemas", root), { recursive: true, force: true });
mkdirSync(new URL("schemas/events", root), { recursive: true });
mkdirSync(new URL("docs", root), { recursive: true });

for (const [name, value] of Object.entries(contracts)) {
  if (value instanceof z.ZodType) write(`schemas/${name}.json`, toJson(value));
}

const fieldType = (field: JsonSchema) =>
  field.enum
    ? field.enum.map((value) => `\`${JSON.stringify(value)}\``).join(" \\| ")
    : `${field.type ?? "any"}${field.format ? ` (${field.format})` : ""}`;

const lines = [
  "# Event reference",
  "",
  "Generated by `npm run generate` from the event registry in `src/events.ts`. Do not edit this file.",
  "",
  "Each event has the envelope `EventEnvelopeV1` (ARCHITECTURE section 5). The tables show the payload.",
  "",
  "| Type | Schema version | Meaning | JSON Schema |",
  "| ---- | -------------- | ------- | ----------- |",
];
const sections: string[] = [];

for (const { type, schemaVersion, payload, schema } of eventCatalog) {
  const file = `events/${type}.v${String(schemaVersion)}.json`;
  write(`schemas/${file}`, toJson(schema));
  const meaning = payload.description ?? "";
  lines.push(
    `| \`${type}\` | ${String(schemaVersion)} | ${meaning} | [${file}](../schemas/${file}) |`,
  );
  const json = z.toJSONSchema(payload, { io: "input" }) as JsonSchema;
  sections.push(
    "",
    `## ${type} v${String(schemaVersion)}`,
    "",
    meaning,
    "",
    "| Field | Type | Required |",
    "| ----- | ---- | -------- |",
    ...Object.entries(json.properties ?? {}).map(
      ([key, field]) =>
        `| \`${key}\` | ${fieldType(field)} | ${json.required?.includes(key) ? "yes" : "no"} |`,
    ),
  );
}

write("docs/events.md", [...lines, ...sections, ""].join("\n"));
